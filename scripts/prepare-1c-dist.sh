#!/bin/bash
# =============================================================================
# Подготовка файлов 1С для Docker-сборки
# =============================================================================
# Запустите ПОСЛЕ ручной установки 1С на хосте через setup-full-*.run
# =============================================================================

set -e

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
DIST_DIR="$SCRIPT_DIR/../docker/1c-server/dist"

echo "============================================================"
echo "Подготовка дистрибутива 1С для Docker"
echo "============================================================"

if [ ! -d "/opt/1cv8" ]; then
    echo "ОШИБКА: 1С не установлена на хосте!"
    echo "Установите 1С вручную:"
    echo "  cd docker/1c-server/dist"
    echo "  sudo ./setup-full-*.run"
    echo "  (выберите русский язык, все компоненты, подтвердите установку)"
    exit 1
fi

echo "Копирование /opt/1cv8 → $DIST_DIR/opt-1cv8 ..."
mkdir -p "$DIST_DIR"

# Копируем с сохранением прав
sudo cp -a /opt/1cv8 "$DIST_DIR/opt-1cv8"

# Меняем владельца на текущего пользователя (для Docker build)
sudo chown -R "$(id -u):$(id -g)" "$DIST_DIR/opt-1cv8"

echo ""
echo "Готово! Теперь можно собирать Docker-образ:"
echo "  cd docker && docker-compose build 1c-server-1"
echo "============================================================"
