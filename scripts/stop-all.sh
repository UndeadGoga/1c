#!/bin/bash
# =============================================================================
# Остановка всей инфраструктуры
# =============================================================================
set -e

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_DIR="$(dirname "$SCRIPT_DIR")"

echo "Остановка инфраструктуры..."

cd "$PROJECT_DIR"
docker compose down

echo "Инфраструктура остановлена."
